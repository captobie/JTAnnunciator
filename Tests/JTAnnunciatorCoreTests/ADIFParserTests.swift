import XCTest
@testable import JTAnnunciatorCore

final class ADIFParserTests: XCTestCase {
    func testParsesRecordsAfterHeader() {
        let adif = """
        Generated by Wavelog
        <ADIF_VER:5>3.1.4<PROGRAMID:7>Wavelog<EOH>
        <CALL:5>K1ABC<BAND:3>20M<MODE:3>FT8<QSO_DATE:8>20260101<TIME_ON:6>123456<STATE:2>CT<EOR>
        <CALL:6>JA8CPF<BAND:3>40M<MODE:3>FT4<QSO_DATE:8>20251231<TIME_ON:4>2359<EOR>
        """

        let qsos = ADIFParser.qsos(fromADIF: adif)

        XCTAssertEqual(qsos.count, 2)
        XCTAssertEqual(qsos[0].callsign, "K1ABC")
        XCTAssertEqual(qsos[0].band, "20M")
        XCTAssertEqual(qsos[0].mode, "FT8")
        XCTAssertEqual(qsos[0].state, "CT")
        XCTAssertEqual(qsos[0].date, Date(timeIntervalSince1970: 1_767_270_896))
        XCTAssertEqual(qsos[1].callsign, "JA8CPF")
        XCTAssertEqual(qsos[1].date, Date(timeIntervalSince1970: 1_767_225_540))
    }

    func testNoHeaderStillParses() {
        let adif = "<call:5>W9XYZ<band:3>15M<mode:3>FT8<eor>"
        XCTAssertEqual(ADIFParser.qsos(fromADIF: adif).map(\.callsign), ["W9XYZ"])
    }

    func testRecordWithoutCallIsSkipped() {
        let adif = "<BAND:3>20M<MODE:3>FT8<EOR><CALL:5>K1ABC<EOR>"
        XCTAssertEqual(ADIFParser.qsos(fromADIF: adif).map(\.callsign), ["K1ABC"])
    }

    func testMissingDateFieldsLeaveDateNil() {
        let adif = "<CALL:5>K1ABC<EOR>"
        XCTAssertNil(ADIFParser.qsos(fromADIF: adif).first?.date)
    }

    func testEmptyInputProducesNoRecords() {
        XCTAssertEqual(ADIFParser.qsos(fromADIF: ""), [])
    }
}
